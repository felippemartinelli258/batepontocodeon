CREATE SCHEMA IF NOT EXISTS codeon_ponto;
SET search_path TO codeon_ponto, public;

CREATE TABLE IF NOT EXISTS usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  senha_salt TEXT NOT NULL,
  cargo TEXT,
  vinculo TEXT NOT NULL DEFAULT 'colaborador',
  perfil TEXT NOT NULL DEFAULT 'colaborador',
  escala_json TEXT,
  status TEXT NOT NULL DEFAULT 'ativo',
  telefone TEXT,
  senha_trocada_em TEXT,
  senha_provisoria INTEGER NOT NULL DEFAULT 0,
  criado_em TEXT NOT NULL,
  atualizado_em TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS usuarios_equipe (
  gestor_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  colaborador_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  PRIMARY KEY (gestor_id, colaborador_id)
);

CREATE TABLE IF NOT EXISTS turnos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL UNIQUE,
  descricao TEXT,
  inicio TEXT NOT NULL,
  fim TEXT NOT NULL,
  ativo INTEGER NOT NULL DEFAULT 1,
  criado_em TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS pontos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  data TEXT NOT NULL,
  hora TEXT NOT NULL,
  dia_ref TEXT NOT NULL,
  ts BIGINT NOT NULL DEFAULT 0,
  tipo TEXT NOT NULL,
  origem TEXT NOT NULL DEFAULT 'automatico',
  justificativa TEXT,
  status TEXT NOT NULL DEFAULT 'aprovado',
  criado_em TEXT NOT NULL,
  criado_por BIGINT REFERENCES usuarios(id),
  ip TEXT
);

CREATE TABLE IF NOT EXISTS ausencias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  data TEXT NOT NULL,
  tipo TEXT NOT NULL DEFAULT 'falta',
  justificativa TEXT,
  status TEXT NOT NULL DEFAULT 'pendente',
  registrado_por BIGINT REFERENCES usuarios(id),
  criado_em TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS solicitacoes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  data TEXT NOT NULL,
  tipo TEXT NOT NULL DEFAULT 'correcao',
  descricao TEXT,
  pontos_json TEXT,
  justificativa TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pendente',
  revisor_id BIGINT REFERENCES usuarios(id),
  revisor_comentario TEXT,
  revisado_em TEXT,
  criado_em TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS avisos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo TEXT NOT NULL,
  corpo TEXT NOT NULL,
  autor_id BIGINT REFERENCES usuarios(id),
  publicado_em TEXT NOT NULL,
  ativo INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS auditoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ator_id BIGINT REFERENCES usuarios(id),
  acao TEXT NOT NULL,
  entidade TEXT NOT NULL,
  entidade_id TEXT,
  detalhes TEXT,
  data_hora TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS sessoes (
  token TEXT PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  criado_em TEXT NOT NULL,
  expira_em TEXT NOT NULL,
  ip TEXT,
  user_agent TEXT
);

CREATE TABLE IF NOT EXISTS config (
  chave TEXT PRIMARY KEY,
  valor TEXT
);

CREATE TABLE IF NOT EXISTS acessos (
  token TEXT PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  rotulo TEXT,
  criado_por BIGINT REFERENCES usuarios(id),
  criado_em TEXT NOT NULL,
  expira_em TEXT,
  ultimo_uso_em TEXT,
  usos INTEGER NOT NULL DEFAULT 0,
  revogado_em TEXT
);

CREATE INDEX IF NOT EXISTS idx_acessos_usuario ON acessos(usuario_id);

CREATE INDEX IF NOT EXISTS idx_pontos_ud ON pontos(usuario_id, dia_ref);
CREATE INDEX IF NOT EXISTS idx_pontos_data ON pontos(data);
CREATE INDEX IF NOT EXISTS idx_ausencias_ud ON ausencias(usuario_id, data);
CREATE INDEX IF NOT EXISTS idx_solic_ud ON solicitacoes(usuario_id, data);
CREATE INDEX IF NOT EXISTS idx_auditoria_data ON auditoria(data_hora);

REVOKE ALL ON SCHEMA codeon_ponto FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL TABLES IN SCHEMA codeon_ponto FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA codeon_ponto FROM PUBLIC, anon, authenticated;
